/** 省级行政区名列表（选择器左栏） */
export const PROVINCES: string[] = REGIONS.map((r) => r.province);

/** 取某省的城市列表；省名不存在时返回空数组（调用方需容忍） */
export function citiesOf(province: string): string[] {
  return REGIONS.find((r) => r.province === province)?.cities ?? [];
}

export interface RegionHit {
  province: string;
  city: string;
}

/**
 * 关键词检索（城市名命中优先，其次省名命中）。
 * 空关键词返回空数组 —— 由调用方决定「空关键词 = 浏览模式」。
 */
export function searchRegions(keyword: string): RegionHit[] {
  const kw = keyword.trim();
  if (kw === '') return [];
  const hits: RegionHit[] = [];
  for (const r of REGIONS) {
    const provinceHit = r.province.includes(kw);
    for (const c of r.cities) {
      if (c.includes(kw) || provinceHit) hits.push({ province: r.province, city: c });
    }
  }
  // 城市名直接命中的排前面，避免搜「大理」时被「云南」整省结果盖住
  return hits.sort((a, b) => {
    const am = a.city.includes(kw) ? 0 : 1;
    const bm = b.city.includes(kw) ? 0 : 1;
    return am - bm || a.city.length - b.city.length;
  });
}

/**
 * 目的地默认省份 —— 用于打开选择器时定位到用户最可能选的那一栏。
 * 传入已有目的地名，若能匹配到某个城市则返回其省份。
 */
export function provinceOfCity(city: string): string | null {
  for (const r of REGIONS) {
    if (r.province === city || r.cities.includes(city)) return r.province;
  }
  return null;
}
