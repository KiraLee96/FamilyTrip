/**
 * 内置地区数据 —— 目的地选择器的数据源
 * ============================================================================
 * 为什么内置而不走接口：
 *   · 行程目的地是**低频、离线可编辑**的字段（新建行程时还没有网也能填）；
 *   · 微信小程序 `<picker mode="region">` 只在 weapp 端存在，H5 端没有对应实现，
 *     用它就等于双端行为分叉（组件不 fork 是硬约束）；
 *   · 因此这里给一份同构可用的静态表：省级行政区（34 个）+ 每省常用目的地城市，
 *     两端共用同一个组件、同一份数据。
 *
 * 数据口径：
 *   · 省级名称与官方一致（带「省 / 市 / 自治区 / 特别行政区」后缀）；
 *   · 城市只收**常用目的地**（省会 + 地级市 + 主要旅游城市），不是全量行政区划表。
 *     全量 333 个地级行政区划应由服务端统一下发（见派发单
 *     D-2026-10-22-01 §5「地区字典下沉」），客户端不再自带全量表。
 *   · 表里没有的地方不走「找不到就报错」的路线：搜索框输入任意文字可直接当目的地，
 *     保证用户永远不被数据表卡住。
 */

